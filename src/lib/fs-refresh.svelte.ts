/**
 * **"저 백엔드의 목록이 낡았다" 는 신호 하나** (docs/log/2026-09-04-fs-cross-place-move.md).
 *
 * 다른 곳 사이의 **이동**이 생기면서 필요해졌다. 이동은 두 자리를 바꾼다 — 목적지에 파일이
 * 생기고 **출발지에서 사라진다**. 목적지는 조작을 시작한 타일 자신이라 끝나고 스스로 다시
 * 읽지만, 출발지는 **다른 타일**이다. 그 타일이 모르면 화면에는 이미 없는 파일이 남아
 * 있고, 그것을 누르면 그제야 "없습니다" 가 뜬다.
 *
 * ## 왜 프롭(`refreshKey`)이 아니라 모듈 상태인가
 *
 * `SftpBrowser.refreshKey` 는 이미 있는 길이지만 **상위에서 내려오는 값**이다 (업로드 모달이
 * 끝났다는 소식을 `+page` → `PaneHost` → 브라우저로 흘린다). 여기서 필요한 것은 타일 →
 * **형제 타일** 이라, 그 길로 보내려면 소식이 상위까지 올라갔다 내려와야 한다 — 중간의
 * 두 컴포넌트가 파일 조작을 하나도 모르는데 그것을 나르는 프롭만 늘어난다.
 *
 * 클립보드(`fs-clipboard.svelte.ts`)가 같은 이유로 모듈 상태인 것과 같은 판단이다.
 *
 * ## 창은 넘지 않는다
 *
 * 창마다 웹뷰가 따로라 모듈도 따로다. 창을 넘는 드래그로 옮겨지는 짐은 **로컬 짐뿐이고**
 * (원격 짐은 세션 번호가 창마다 달라 거절된다 — `fs-drag.ts`), 그때 반대편 창의 로컬 타일은
 * 새로고침 신호를 받지 못한다. ⟳ 한 번이면 되는 일이라 창 사이 통로를 새로 파지 않는다.
 */

/**
 * 신호 한 칸 — **어느 백엔드가**(`key`) **몇 번째로**(`tick`) 낡았는가.
 *
 * 키마다 카운터를 두지 않고 하나로 합친 이유: 듣는 쪽이 "내 것인가" 를 `key` 비교로 한 번에
 * 답할 수 있고, 남의 신호에는 아무 일도 하지 않으므로 카운터를 쪼갤 이득이 없다.
 */
const store = $state<{ tick: number; key: string }>({ tick: 0, key: "" });

/**
 * 이 백엔드를 보고 있는 타일들에게 "다시 읽어라" 고 알린다 — **새 `tick` 을 돌려준다**.
 *
 * 돌려주는 값이 계약의 절반이다: 신호를 보낸 타일은 대개 방금 스스로 다시 읽은 참이라
 * (자기가 목적지다) 그 값을 자기 소비 표시로 적어 두면 **자기 신호에 한 번 더 읽는 일**이
 * 없다.
 */
export function notifyFsRefresh(key: string): number {
  store.tick += 1;
  store.key = key;
  return store.tick;
}

/**
 * 지금 신호 — `$effect` 안에서 읽으면 구독이 걸린다 (밖에서 읽으면 그냥 현재 값이다).
 * 돌려주는 것은 룬 객체 그 자신이라 **가지고 있지 말고 그 자리에서 읽어야** 한다.
 */
export function fsRefreshSignal(): { readonly tick: number; readonly key: string } {
  return store;
}
